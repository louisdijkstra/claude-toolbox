#!/usr/bin/env node

/**
 * Stop Hook: Session End
 *
 * Runs when Claude Code session ends.
 * Extracts patterns and saves learnings.
 */

const fs = require('fs');
const path = require('path');

// Get project root from environment or current directory
const projectRoot = process.env.PWD || process.cwd();
// Must match statusline.sh, which also honours CLAUDE_CONFIG_DIR — otherwise the
// two hooks disagree about where the session cost file lives.
const claudeDir = process.env.CLAUDE_CONFIG_DIR || path.join(process.env.HOME, '.claude');
const sessionsDir = path.join(claudeDir, 'sessions');
const observationsFile = path.join(claudeDir, 'observations.jsonl');

// Ensure directories exist
if (!fs.existsSync(sessionsDir)) {
  fs.mkdirSync(sessionsDir, { recursive: true });
}

// Generate session filename
const now = new Date();
const timestamp = now.toISOString().replace(/[:.]/g, '-').slice(0, -5);
const date = now.toISOString().slice(0, 10);
const sessionFile = path.join(sessionsDir, `${date}-${timestamp.slice(11)}.md`);

// Fold this session's cost into the ledger. reconcile() is keyed by session id
// and idempotent, so running it here is safe even though the statusline has
// already recorded the same session, and skipping it (hook never fires, machine
// crashes) only delays the entry rather than losing it.
try {
  fs.readFileSync(0, 'utf8'); // consume the hook payload so the writer never blocks
} catch (_) {}

try {
  const { reconcile } = require('../../scripts/budget.js');
  reconcile(claudeDir);
} catch (err) {
  console.error(`[Hook] Error updating budget ledger: ${err.message}`);
}

// The cost files stay on disk — the ledger dedupes by session id, so an extra
// copy costs nothing, while deleting one would lose the only record of a session
// whose transcript never got a cost-state entry. Drop only the long-dead ones
// that the ledger has definitely absorbed.
try {
  const { readLedger } = require('../../scripts/budget.js');
  const known = readLedger(claudeDir).sessions || {};
  const costsDir = path.join(claudeDir, '.session_costs');
  const cutoff = now.getTime() - 60 * 24 * 60 * 60 * 1000;
  for (const name of fs.readdirSync(costsDir)) {
    const file = path.join(costsDir, name);
    if (!known[name]) continue;
    if (fs.statSync(file).mtimeMs > cutoff) continue;
    fs.unlinkSync(file);
  }
} catch (_) {}

// Get basic session info
const sessionInfo = {
  timestamp: now.toISOString(),
  project: projectRoot,
  duration: process.env.CLAUDE_SESSION_DURATION || 'unknown',
};

// Create session summary
const summary = `# Session Summary

**Date**: ${date}
**Time**: ${timestamp.slice(11)}
**Project**: ${projectRoot}
**Duration**: ${sessionInfo.duration}

## Session Notes

[Auto-generated session end summary]

This session has ended. Key observations will be extracted for continuous learning.

## Next Steps

- Review session transcript if needed
- Check for new instincts in \`.claude/instincts/\`
- Run \`/instinct-status\` to see learned patterns

---

*Auto-generated by session-end hook*
`;

// Save session summary
try {
  fs.writeFileSync(sessionFile, summary, 'utf8');
  console.error(`[Hook] Session summary saved: ${sessionFile}`);
} catch (err) {
  console.error(`[Hook] Error saving session summary: ${err.message}`);
}

// Append observation to JSONL for later analysis
const observation = {
  timestamp: now.toISOString(),
  project: projectRoot,
  type: 'session_end',
  sessionFile: sessionFile,
};

try {
  fs.appendFileSync(observationsFile, JSON.stringify(observation) + '\n', 'utf8');
} catch (err) {
  console.error(`[Hook] Error logging observation: ${err.message}`);
}

// Exit successfully
process.exit(0);
